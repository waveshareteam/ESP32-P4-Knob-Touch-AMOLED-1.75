#!/usr/bin/env python3
"""Write the GBK to Unicode table used by components/text_codec.

Every two-byte GBK character (lead 0x81-0xFE, trail 0x40-0xFE) maps to one BMP code point;
codes GBK leaves unassigned map to 0.

    python3 tools/gen_gbk_table.py components/text_codec/gbk_table.c
"""

import sys

LEADS = range(0x81, 0xFF)
TRAILS = range(0x40, 0xFF)


def code_point(lead, trail):
    if trail == 0x7F:
        return 0
    try:
        text = bytes([lead, trail]).decode("gbk")
    except UnicodeDecodeError:
        return 0
    return ord(text) if len(text) == 1 and ord(text) <= 0xFFFF else 0


def main():
    values = [code_point(lead, trail) for lead in LEADS for trail in TRAILS]
    rows = []
    for i in range(0, len(values), 12):
        rows.append("    " + ", ".join("0x%04X" % v for v in values[i:i + 12]) + ",")
    body = "\n".join(rows)
    with open(sys.argv[1], "w", encoding="ascii") as f:
        f.write(f"""/*
 * SPDX-FileCopyrightText: 2026 Waveshare
 *
 * SPDX-License-Identifier: Apache-2.0
 */

/* Generated by tools/gen_gbk_table.py from the GBK code page; do not edit */

#include <stdint.h>

/* [lead - 0x81][trail - 0x40], 0 where GBK assigns no character */
const uint16_t text_codec_gbk_table[{len(LEADS)} * {len(TRAILS)}] = {{
{body}
}};
""")
    print(f"{sum(1 for v in values if v)} characters")


if __name__ == "__main__":
    main()
